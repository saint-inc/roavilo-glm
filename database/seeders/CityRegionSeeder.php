    public function run(): void
    {
        foreach (self::CITIES as $i => [$name, $slug, $hot, $districts]) {
            // 城市不存在才创建（幂等）
            $city = City::firstOrCreate(
                ['slug' => $slug],
                ['name' => $name, 'is_hot' => $hot, 'sort' => $i]
            );

            // 该城市的行政区（不存在才创建）
            foreach ($districts as $di => $district) {
                Region::firstOrCreate(
                    ['city_id' => $city->id, 'name' => $district],
                    ['sort' => $di]
                );
            }
        }

        $this->command->info('城市/行政区 Seed 完成：'.count(self::CITIES).' 个城市、'
            .Region::count().' 个行政区');
    }
